#!/usr/bin/env python3
"""Turn crates/ui/assets/icons/*.svg into crates/ui/src/icons.rs.

The sidebar must not carry hand-written paths (they were written blind and never
rendered). These come from Lucide (ISC, see assets/icons/LICENSE-lucide.txt):
clean 24x24 stroke icons that inherit `currentColor`, so light and dark mode work
with no extra CSS.

Usage:
  python3 scripts/make_icons.py            # regenerate icons.rs from the .svg files
  python3 scripts/make_icons.py --fetch    # re-download the wanted icons first
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "crates/ui/assets/icons"
OUT = ROOT / "crates/ui/src/icons.rs"

# Rust name -> Lucide file
ICONS = {
    "sell": "shopping-cart",
    "sales": "receipt-text",
    "carnet": "notebook-tabs",
    "products": "package",
    "expenses": "wallet",
    "settings": "sliders-horizontal",
    "session": "clock",
    "journal": "history",
    "search": "search",
    "plus": "plus",
    "chevron_start": "chevron-left",
    "collapse": "panel-left-close",
    "expand": "panel-left-open",
    "menu": "ellipsis",
    "sun": "sun",
    "moon": "moon",
    "edit": "pencil",
    "trash": "trash-2",
    "camera": "camera",
    "image": "image",
    "print": "printer",
    "check": "check",
    "close": "x",
    "undo": "rotate-ccw",
    "warning": "circle-alert",
    "empty": "ban",
}


def fetch() -> None:
    """Re-download the icons we actually use from the npm registry."""
    version = "1.60.0"
    SRC.mkdir(parents=True, exist_ok=True)
    tmp = Path("/tmp/lucide-icons")
    subprocess.run(
        ["bash", "-c",
         f"rm -rf {tmp} && mkdir -p {tmp} && cd {tmp} && "
         f"curl -sL https://registry.npmjs.org/lucide-static/-/lucide-static-{version}.tgz "
         f"-o l.tgz && tar xzf l.tgz"],
        check=True,
    )
    for name in ICONS.values():
        src = tmp / "package" / "icons" / f"{name}.svg"
        if src.exists():
            (SRC / f"{name}.svg").write_text(src.read_text())
    (SRC / "LICENSE-lucide.txt").write_text(
        (tmp / "package" / "LICENSE").read_text()
    )
    print(f"downloaded {len(ICONS)} icons (v{version})")


def inner(svg: str) -> str:
    """Everything inside <svg>…</svg>, on one line, no licence comment."""
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    body = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    body = re.sub(r"\s+", " ", body).strip()
    return body.replace('"', "'")


def main() -> None:
    if "--fetch" in sys.argv:
        fetch()

    entries = []
    for rust_name, file in sorted(ICONS.items()):
        path = SRC / f"{file}.svg"
        if not path.exists():
            sys.exit(f"missing icon: {path}")
        body = inner(path.read_text()).replace("\\", "\\\\")
        entries.append(f'        "{rust_name}" => r#"{body}"#,')

    OUT.write_text(
        "//! Icon set — generated by `scripts/make_icons.py`, do not edit by hand.\n"
        "//!\n"
        "//! Source: Lucide " + "1.60.0" + " (ISC licence, see `assets/icons/LICENSE-lucide.txt`).\n"
        "//! Each entry is the *inside* of a 24x24 `<svg>` that inherits\n"
        "//! `currentColor`, so the same icon works in light and dark mode.\n"
        "\n"
        "/// Inner markup of an icon. Unknown names fall back to a neutral dot so a\n"
        "/// typo is a small blemish, never a broken page.\n"
        "pub fn paths(name: &str) -> &'static str {\n"
        "    match name {\n"
        + "\n".join(entries)
        + "\n"
        '        _ => r#"<circle cx="12" cy="12" r="3"/>"#,\n'
        "    }\n"
        "}\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({len(entries)} icons)")


if __name__ == "__main__":
    main()
